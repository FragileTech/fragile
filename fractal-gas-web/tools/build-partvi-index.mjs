// Build lecture metadata and a reproducible formula-to-workbench source index.
import { readFile, writeFile, mkdir } from "node:fs/promises";
import { createHash } from "node:crypto";
const root = new URL("../../", import.meta.url);
const read = async (p) => JSON.parse(await readFile(new URL(p, root), "utf8"));
const spec = await read(
  "fractal-gas-web/web/euclidean-gas/lecture/partvi-spec.json",
);
const qftControls = await read(
  "fractal-gas-web/web/euclidean-gas/lecture/partvi-qft-controls.json",
);
const fieldControls = await read(
  "algorithmic-gas/crates/algorithmic-gas/src/physics/fields-controls.json",
);
const controls = { ...qftControls, ...fieldControls };
for (const d of spec) {
  if (!controls[d.experiment]) throw new Error("Missing controls " + d.id);
  d.controls = controls[d.experiment];
}
await writeFile(
  new URL("fractal-gas-web/web/euclidean-gas/lecture/partvi-metadata.js", root),
  "// Generated by tools/build-partvi-index.mjs from the reviewed experiment specification.\nexport const metadata = " +
    JSON.stringify(spec, null, 2) +
    ";\n",
);
const placementPath =
  "fractal-gas-web/web/euclidean-gas/lecture/placements.json";
const placements = (await read(placementPath)).filter((x) => x.part !== "VI");
placements.push(
  ...spec.map(({ id, part, title, chapter, target }) => ({
    id,
    part,
    title,
    chapter,
    target,
  })),
);
await writeFile(
  new URL(placementPath, root),
  JSON.stringify(placements, null, 2) + "\n",
);
const captionPath = "fractal-gas-web/web/euclidean-gas/lecture/captions.json";
const captions = await read(captionPath);
for (const d of spec)
  captions[d.id] = { question: d.question, prediction: d.prediction };
await writeFile(
  new URL(captionPath, root),
  JSON.stringify(captions, null, 2) + "\n",
);
const entries = [];
for (const chapter of [...new Set(spec.map((d) => d.chapter))]) {
  const source = await readFile(
    new URL("docs/" + chapter + ".md", root),
    "utf8",
  );
  const lines = source.split("\n");
  const local = spec.filter((d) => d.chapter === chapter);
  // Stable explicit anchors are matched exactly; other blocks link to their nearest
  // preceding workbench section. The index describes reading coverage, not a passed test.
  const positions = local.map((d) => ({
    demo: d,
    line: lines.findIndex(
      (x) =>
        x.trim() === `(${d.target})=` || x.trim() === `:label: ${d.target}`,
    ),
  }));
  for (const p of positions)
    if (p.line < 0)
      throw new Error(
        "Missing chapter anchor " + p.demo.target + " for " + p.demo.id,
      );
  const select = (line) => {
    const prior = positions
      .filter((p) => p.line <= line)
      .sort((a, b) => b.line - a.line);
    return (prior[0] || positions.toSorted((a, b) => a.line - b.line)[0]).demo;
  };
  let section = "",
    mathStart = -1,
    formal = null;
  for (let i = 0; i < lines.length; i++) {
    const anchor = lines[i].match(/^\(([^)]+)\)=$/);
    if (anchor) section = anchor[1];
    const directive = lines[i].match(
      /^\s*[:`]{3,}\{prf:(theorem|lemma|proposition|corollary|definition|assumption|axiom|proof)\}\s*(.*)/,
    );
    if (directive) {
      const d = select(i);
      formal = {
        kind: directive[1],
        title: directive[2],
        label: section + "-" + directive[1] + "-" + (i + 1),
        chapter,
        line: i + 1,
        section,
        experiment: d.id,
        relationship: "linked calculation and assumptions",
        validation: d.validation,
      };
      entries.push(formal);
    }
    const label = lines[i].match(/^\s*:label:\s*(\S+)/);
    if (label && formal) {
      formal.label = label[1];
      const d = select(i);
      formal.experiment = d.id;
      formal.validation = d.validation;
      formal = null;
    }
    if (/^\s*[:`]{3,}\s*$/.test(lines[i])) formal = null;
    if (lines[i].trim() === "$$") {
      if (mathStart < 0) mathStart = i;
      else {
        const text = lines.slice(mathStart + 1, i).join("\n");
        const hash = createHash("sha256")
          .update(text)
          .digest("hex")
          .slice(0, 12);
        const d = select(mathStart);
        entries.push({
          kind: "display_math",
          label: "equation-" + hash,
          chapter,
          line: mathStart + 1,
          section,
          experiment: d.id,
          expression: text,
          relationship: "formula in linked proof/definition family",
        });
        mathStart = -1;
      }
    }
  }
}
const output = "docs/source/2_fractal_gas/partvi-experiment-index.json";
await writeFile(
  new URL(output, root),
  JSON.stringify(
    { schema: "fragile-partvi-formula-index-v1", experiments: spec, entries },
    null,
    2,
  ) + "\n",
);
await mkdir(new URL("docs/_static_theory/gas-demos/", root), {
  recursive: true,
});
await writeFile(
  new URL("docs/_static_theory/gas-demos/partvi-formulas.json", root),
  JSON.stringify(entries) + "\n",
);
await writeFile(
  new URL(
    "fractal-gas-web/web/euclidean-gas/lecture/partvi-formulas.json",
    root,
  ),
  JSON.stringify(entries) + "\n",
);
console.log(
  `Indexed ${entries.length} formal/equation blocks across ${spec.length} Part VI workbenches.`,
);
